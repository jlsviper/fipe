# Gate-level regression: 20 random programs (test/regress/, generated by
# bin/gen_regress.ml) with random pin roles, skews, timing-monitor setups,
# FIFO data and random input waveforms on all eight bus pins. Every change on
# every output (protocol pins, output enables, status pins including the
# monitor trigger, MISO) is recorded from reset, then status, samples, monitor
# statistics and debug registers are read back. The record is hashed and
# compared with test/regress/golden.txt, which comes from the RTL. Run on the
# gate-level netlist (make GATES=yes, and CI's gl_test on the real post-layout
# netlist), a match means the gates behaved exactly like the RTL on all of it.
# REGRESS_UPDATE=1 rewrites the golden file (RTL only).

import hashlib
import os
import random

REGRESS_DIR = os.path.join(os.path.dirname(__file__), "regress")
RUN_CYCLES = 3000


def load_regress(path):
    cfg = {"mon": [], "fifo": [], "words": []}
    for line in open(path):
        f = line.split()
        if not f or f[0].startswith("#"):
            continue
        if f[0] == "pins":
            cfg["pins"] = int(f[1], 16)
        elif f[0] == "skew":
            cfg["skew"] = int(f[1], 16)
        elif f[0] == "seed":
            cfg["seed"] = int(f[1])
        elif f[0] == "mon":
            cfg["mon"].append([int(x, 16) for x in f[2:5]])
        elif f[0] == "fifo":
            cfg["fifo"].append(int(f[1], 16))
        elif f[0] == "word":
            cfg["words"].append(int(f[1], 16))
    return cfg


async def record(dut, events):
    """Every change of every output, with its cycle number."""
    last = None
    cycle = 0
    while True:
        await ClockCycles(dut.clk, 1)
        cycle += 1
        now = (str(dut.uo_out.value), str(dut.uio_out.value), str(dut.uio_oe.value))
        if now != last:
            events.append("%d %s %s %s" % ((cycle,) + now))
            last = now


async def drive_inputs(dut, seed):
    """A random waveform on the eight bus inputs: each bit toggles about
    every 40 cycles."""
    rng = random.Random(seed)
    v = 0xFF
    while True:
        for b in range(8):
            if rng.randrange(40) == 0:
                v ^= 1 << b
        dut.uio_in.value = v
        await ClockCycles(dut.clk, 1)


async def run_regress_program(dut, cfg):
    dut.uio_in.value = 0xFF
    dut.ui_in.value = 0b010
    dut.rst_n.value = 0
    await ClockCycles(dut.clk, 10)
    events = []
    rec = cocotb.start_soon(record(dut, events))
    dut.rst_n.value = 1
    await ClockCycles(dut.clk, 10)
    # the program plus NOPs past its halt: every word the registered fetch can
    # reach is defined (unwritten memory is undefined, and RTL and gate-level
    # simulators propagate undefined values differently)
    words = cfg["words"] + [0] * min(4, 64 - len(cfg["words"]))
    for a, w in enumerate(words):
        await write(dut, a, w)
    await write(dut, 0x41, cfg["pins"])
    await write(dut, 0x42, cfg["skew"])
    for s, (wa, wb, wc) in enumerate(cfg["mon"]):
        await write(dut, 0x48 + 3 * s, wa)
        await write(dut, 0x49 + 3 * s, wb)
        await write(dut, 0x4A + 3 * s, wc)
    await write(dut, 0x40, 0b110)  # clear monitors and sample log
    for w in cfg["fifo"]:
        await write(dut, 0x43, w)
    drv = cocotb.start_soon(drive_inputs(dut, cfg["seed"]))
    await write(dut, 0x40, 0b001)  # start
    await ClockCycles(dut.clk, RUN_CYCLES)
    drv.cancel()
    dut.uio_in.value = 0xFF
    for reg in [0x44, 0x45, 0x58, 0x59, 0x5A, 0x5B, 0x5C, 0x60, 0x61, 0x62, 0x63]:
        events.append("read %02x %08x" % (reg, await read(dut, reg)))
    rec.cancel()
    return events


@cocotb.test()
async def test_regress(dut):
    clock = Clock(dut.clk, 20, unit="ns")
    cocotb.start_soon(clock.start())
    dut.ena.value = 1
    names = sorted(n[:-4] for n in os.listdir(REGRESS_DIR) if n.startswith("prog") and n.endswith(".txt"))
    results = {}
    for name in names:
        events = await run_regress_program(dut, load_regress(os.path.join(REGRESS_DIR, name + ".txt")))
        digest = hashlib.sha256("\n".join(events).encode()).hexdigest()[:16]
        results[name] = (len(events), digest)
        dut._log.info("%s: %d output events, %s", name, len(events), digest)
    golden_path = os.path.join(REGRESS_DIR, "golden.txt")
    if os.environ.get("REGRESS_UPDATE") == "1":
        with open(golden_path, "w") as f:
            for name, (n, d) in sorted(results.items()):
                f.write("%s %d %s\n" % (name, n, d))
        dut._log.info("wrote %s", golden_path)
        return
    golden = {}
    for line in open(golden_path):
        name, n, d = line.split()
        golden[name] = (int(n), d)
    bad = [n for n in names if results[n] != golden.get(n)]
    assert not bad, "outputs differ from the RTL golden record for: %s" % ", ".join(bad)
    dut._log.info("all %d random programs match the RTL golden record", len(names))
