(* The host register map: the one source for the top level's decode and
   read-back (hw/tt_top.ml looks every address up here, and checks at
   elaboration that what it can read is exactly what this table says is
   readable) and for docs/registers.md (generated by bin/gen_verilog.ml). *)
open! Base

type access =
  | R
  | W
  | RW

type entry =
  { addr : int
  ; name : string
  ; access : access
  ; doc : string
  }

