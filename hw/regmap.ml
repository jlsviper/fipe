let addr name =
  match List.find table ~f:(fun e -> String.equal e.name name) with
  | Some e -> e.addr
  | None -> raise_s [%message "register not in the map" (name : string)]
;;

let readable =
  List.filter_map table ~f:(fun e ->
    match e.access with
    | R | RW -> Some e.addr
    | W -> None)
;;

let markdown () =
  let access = function
    | R -> "R"
    | W -> "W"
    | RW -> "RW"
  in
  String.concat
    ([ "# FIPE host register map\n\n"
     ; "Generated from `hw/regmap.ml` by `bin/gen_verilog.ml`; do not edit by hand.\n"
     ; "Access is over the host SPI port: an 8-bit command (bit 7 = write, bits 6..0 =\n"
     ; "address) and 32 data bits, MSB first, SPI mode 0.\n\n"
     ; "| Address | Name | Access | Contents |\n| --- | --- | --- | --- |\n"
     ]
     @ List.map table ~f:(fun e ->
       Printf.sprintf "| 0x%02X | %s | %s | %s |\n" e.addr e.name (access e.access) e.doc))
;;
