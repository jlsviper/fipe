(* Random programs for the gate-level regression (test/test_regress.py):
   writes test/regress/progNN.txt, each holding the program words and the
   host setup (pins, skews, monitor configuration, FIFO data, input seed).
   Deterministic: the same seed always gives the same set.
     dune exec bin/gen_regress.exe *)
open! Base
open Stdio
module Isa = Fipe_isa.Isa

let n_programs = 20

let gen rand =
  let ri n = Random.State.int rand n in
  let len = 4 + ri 24 in
  let acts = Isa.Act.[| Drive0; Drive1; Release; Toggle; Shift_out; Sample; Aux0; Aux1 |] in
  let pins = Isa.Wait_pin.[| In; Data; Clk; Aux |] in
  let tos = Isa.Wait_timeout.[| Forever; X_cycles; Y_cycles |] in
  Array.init (len + 1) ~f:(fun a ->
    if a = len
    then Isa.Jmp { cond = Always; addr = a }
    else (
      let r = ri 100 in
      if r < 38
      then Isa.Evt { dt = ri 30; clk_pin = ri 2 = 1; cls = ri 4; act = acts.(ri 8) }
      else if r < 45
      then Dly { dt = ri 80 }
      else if r < 55
      then Set { dst = (if ri 2 = 0 then X else Y); imm = ri 40 }
      else if r < 60
      then Set { dst = Coder_mode; imm = [| 0; 4; 8; 12 |].(ri 4) }
      else if r < 63
      then Set { dst = Prescale; imm = ri 2 }
      else if r < 68
      then Pull { block = true }
      else if r < 78
      then Wait { pin = pins.(ri 4); pol = ri 2 = 1; timeout = tos.(ri 3) }
      else if r < 92 && a > 0
      then
        Jmp
          { cond = [| Isa.Cond.X_dec_nz; Y_dec_nz; Flag; Pin; Always |].(ri 5)
          ; addr = (if ri 3 = 0 then a + 1 + ri (len - a) else ri a)
          }
      else Nop))
;;

let () =
  let rand = Random.State.make [| 2026; 10; 12 |] in
  ignore (Stdlib.Sys.command "mkdir -p test/regress" : int);
  for k = 0 to n_programs - 1 do
    let prog = gen rand in
    let data_pin = Random.State.int rand 8 in
    let clk_pin = (data_pin + 1 + Random.State.int rand 7) % 8 in
    let in_pin = Random.State.int rand 8 in
    let aux_pin = Random.State.int rand 8 in
    let pins_word = data_pin lor (clk_pin lsl 3) lor (in_pin lsl 6) lor (aux_pin lsl 9) in
    let skew = Random.State.bits rand land 0x0F0F0F in
    let word () = Random.State.bits rand land 0xFFFF_FFFF lor (Random.State.int rand 4 lsl 30) in
    let path = Printf.sprintf "test/regress/prog%02d.txt" k in
    Out_channel.with_file path ~f:(fun oc ->
      Out_channel.fprintf oc "# random program %d, generated by bin/gen_regress.ml\n" k;
      Out_channel.fprintf oc "pins %x\nskew %x\nseed %d\n" pins_word skew (Random.State.int rand 1_000_000);
      (* monitor slots 0..3: words A, B, C at 0x48 + 3s *)
      for s = 0 to 3 do
        Out_channel.fprintf oc "mon %d %x %x %x\n" s (word ()) (Random.State.bits rand land 0xFFFF_FFFF) (Random.State.int rand 8)
      done;
      for _ = 1 to 4 do
        Out_channel.fprintf oc "fifo %x\n" (word ())
      done;
      Array.iter prog ~f:(fun i -> Out_channel.fprintf oc "word %04x\n" (Isa.encode i)))
  done;
  printf "wrote %d programs to test/regress/\n" n_programs
;;
